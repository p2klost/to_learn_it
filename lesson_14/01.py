"""
Создайте программу, которая имитирует журнал событий. 
Пользователь вводит сообщения: 
 
Введите сообщение: 
Сервер запущен 
 
Каждое сообщение должно добавляться в log.txt 
Формат: 
 
Сервер запущен 
Пользователь вошёл в систему 
Получен запрос 
 
Условие: старые записи нельзя удалять. 
"""

while True: # про цикл в условии не написано, но подумал стоит добавить, чтобы постоянно не запускать программу для написания сообщения
    
    message = input("Введите сообщение: ")

    file = open(r"lesson_14\01\log.txt","a",encoding="utf-8")

    if message == "exit":
        file.close()
        break
    else:
        file.write(f"{message}\n")