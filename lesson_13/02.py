"""
Напишите программу для имитации банковского перевода. 
Пользователь вводит: 
●  баланс счёта; 
●  сумму перевода. 
Необходимо: 
Преобразовать введённые значения в числа. 
Если сумма перевода больше баланса — вывести сообщение 
об ошибке. 
Если всё прошло успешно — вывести новый баланс. 
Использовать else для вывода сообщения об успешном 
выполнении операции. 
Использовать finally для вывода: Операция завершена. 
 
Обработайте как минимум: 
●  ValueError; 
●  ситуацию недостаточного баланса без создания 
собственного исключения.
"""

try:
    acc_balance = float(input("Введите баланс счёта: "))
    transfer_sum  = float(input("Введите сумму перевода: "))
except ValueError:
    print("Ошибка: необходимо ввести число.")
else:
    if transfer_sum > acc_balance:
        print("Ошибка: сумма перевода больше баланса счёта.")
    else:
        acc_balance -= transfer_sum
        print(f"Операция выполнена успешно. Новый баланс счёта: {acc_balance:.2f}.")
finally:
    print("Операция завершена.")